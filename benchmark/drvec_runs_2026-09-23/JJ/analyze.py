#!/usr/bin/env python3
"""Rank-sequence summary from scan.json + result.json -> RESULTS_rank.md.

For each case and rank: every drvec route (cold / -seedjoh / -multistart 30 /
profiled at Johansen's beta), the best exact logL found, the LR sequence from the
-lrtest run and from the best-found values, Johansen's lambda-max on the same
data, and the largest non-unit root of Johansen's fitted levels VAR (a root > 1
lies outside the region where the exact likelihood is defined)."""
import json
import os

import numpy as np
from statsmodels.tsa.vector_ar.vecm import VECM

HERE = os.path.dirname(os.path.abspath(__file__))
TCN = {1: "tc1", 2: "tc2", 3: "tc3", 4: "tc4", 5: "tc5"}


def read_inp(path):
    L = [l for l in open(path).read().split("\n") if l and not l.startswith("*")]
    n = int(L[1].split()[1])
    return np.array([[float(x) for x in l.split()] for l in L[4:4 + n]])


def joh_maxroot(Y, k, r, det):
    v = VECM(Y, k_ar_diff=k, coint_rank=r, deterministic=det).fit()
    M = Y.shape[1]
    Pi = np.asarray(v.alpha) @ np.asarray(v.beta)[:M].T
    G = [np.asarray(v.gamma)[:, i * M:(i + 1) * M] for i in range(k)]
    A = [np.eye(M) + Pi + (G[0] if k else 0)]
    for i in range(1, k):
        A.append(G[i] - G[i - 1])
    if k:
        A.append(-G[k - 1])
    p = len(A)
    C = np.zeros((M * p, M * p))
    C[:M] = np.hstack(A)
    if p > 1:
        C[M:, :-M] = np.eye(M * (p - 1))
    ev = np.linalg.eigvals(C)
    # drop the M-r eigenvalues closest to +1 (the unit roots the rank imposes),
    # then report the largest remaining modulus
    idx = np.argsort(np.abs(ev - 1.0))[M - r:]
    rest = np.abs(ev[idx])
    return float(rest.max()), None


def cell(d):
    if d["logL"] is None:
        return "FAIL(%s)" % d.get("fail", "rc=%s" % d["rc"]).split("\n")[-1].strip()
    tc = d["termcodes"]
    if "best_start" in d:
        # banner list only covers converged starts; report best start index
        return "%.3f (best start %d; %s)" % (d["logL"], d["best_start"],
                                             "tcs " + "".join(str(t) for t in tc))
    return "%.3f %s" % (d["logL"], TCN.get(tc[-1], "?") if tc else "?")


def main():
    out = ["# drvec rank-by-rank optimum audit (q = 0) — generated by analyze.py\n",
           "Columns: exact logL and optimizer termcode (tc1 gradient, tc2 steptol, "
           "tc3 'no lower point', tc4 iteration limit). `johfix` = exact logL profiled "
           "at Johansen's beta (-fixb2 0 on data with Y1 replaced by Johansen's W): a "
           "LOWER BOUND for the free optimum. `J maxroot` = largest root modulus of "
           "Johansen's fitted levels VAR after removing the M-r unit roots (>1 = "
           "explosive, outside the exact likelihood's domain).\n"]
    order = ["denmark", "denmark5", "finland", "finland_const", "UKconinc", "UKconinc_seas",
             "UKconsumption", "UKconsumption_lev", "Canada", "UKpppuip"]
    for name in order:
        cdir = os.path.join(HERE, "cases", name)
        if not os.path.exists(os.path.join(cdir, "scan.json")):
            continue
        res = json.load(open(os.path.join(cdir, "result.json")))
        sc = json.load(open(os.path.join(cdir, "scan.json")))
        M, p, case = res["M"], res["p"], res["drcase"]
        det = {2: "ci", 3: "co"}[case]
        Y = read_inp(os.path.join(cdir, name + ".inp"))
        cj = res["cajo_same"]
        lr_ll = {x["r"]: x["logL"] for x in res["dr_lr"]["ranks"]}
        lr_tc = [b["termcode"] for b in res["dr_lr"]["banners"]]
        out.append("## %s (M=%d, p=%d, case %d)\n" % (name, M, p, case))
        out.append("| r | -lrtest logL | cold | -seedjoh | -multistart 30 | johfix | johfix+ms20 | best | J cond. logL | J maxroot |")
        out.append("|---|---|---|---|---|---|---|---|---|---|")
        best = {0: sc["r0_lrtest"]}
        out.append("| 0 | %.3f %s | | | | | | %.3f | %.3f | - |"
                   % (lr_ll[0], TCN[lr_tc[0]], sc["r0_lrtest"], cj["logL"][0]))
        for r in range(1, M):
            row = sc["ranks"][str(r)]
            best[r] = row["best"][1]
            mr, _ = joh_maxroot(Y, p - 1, r, det)
            flag = ""
            if row["johfix"]["logL"] and row["johfix"]["logL"] > max(
                    x for x in [row["cold"]["logL"], row["seedjoh"]["logL"], row["ms30"]["logL"]]
                    if x is not None) + 1e-4:
                flag = " **>free**"
            out.append("| %d | %.3f %s | %s | %s | %s | %s%s | %s | %.3f (%s) | %.3f | %.4f%s |"
                       % (r, lr_ll[r], TCN.get(lr_tc[r], "?") if r < len(lr_tc) else "?",
                          cell(row["cold"]), cell(row["seedjoh"]), cell(row["ms30"]),
                          cell(row["johfix"]), flag, cell(row["johfix_ms"]),
                          row["best"][1], row["best"][0], cj["logL"][r], mr,
                          " (explosive)" if mr > 1.0 + 1e-6 else ""))
        lr_seq = [2 * (lr_ll[i + 1] - lr_ll[i]) for i in range(M - 1)]
        best_seq = [2 * (best[i + 1] - best[i]) for i in range(M - 1)]
        cve = [row[1] for row in cj["cv_eigen"]]
        out.append("")
        out.append("| r0 | M-r | LR drvec -lrtest | LR drvec best-found | Johansen lambda-max (same data) | 5% cv |")
        out.append("|---|---|---|---|---|---|")
        for i in range(M - 1):
            out.append("| %d | %d | %.2f | %.2f | %.2f | %.2f |"
                       % (i, M - i, lr_seq[i], best_seq[i], cj["eigen"][i], cve[i]))
        out.append("| %d | 1 | not expressible (r=M) | - | %.2f | %.2f |"
                   % (M - 1, cj["eigen"][M - 1], cve[M - 1]))

        def seqr(s):
            for i, (a, c) in enumerate(zip(s, cve)):
                if a <= c:
                    return str(i)
            return str(M) if len(s) == M else "%d+ (r=M untestable)" % (M - 1)
        jr = seqr(cj["eigen"])
        out.append("\nrank (sequential lambda-max, 5%%): drvec -lrtest r=%s; drvec best-found r=%s; "
                   "Johansen same data r=%s\n" % (seqr(lr_seq), seqr(best_seq), jr))
        json.dump({"best": best, "lr_seq": lr_seq, "best_seq": best_seq},
                  open(os.path.join(cdir, "analysis.json"), "w"), indent=1)
    open(os.path.join(HERE, "RESULTS_rank.md"), "w").write("\n".join(out))
    print("\n".join(out))


if __name__ == "__main__":
    main()
